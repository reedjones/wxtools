/**
 * Template renderer interface
 */
export interface TemplateRenderer {
  render(template: string, data: Record<string, any>): string;
}

/**
 * Simple template engine for runtime and build-time code generation
 */
export class TemplateEngine implements TemplateRenderer {
  private helpers = new Map<string, (...args: any[]) => any>();

  /**
   * Register a helper function
   */
  registerHelper(name: string, fn: (...args: any[]) => any): void {
    this.helpers.set(name, fn);
  }

  /**
   * Render a template with data
   * Supports {{variable}}, {{helper arg1 arg2}}, and {{#if}}/{{#each}} blocks
   */
  render(template: string, data: Record<string, any>): string {
    let result = template;

    // Replace variables: {{variable}}
    result = result.replace(/\{\{([^}#/][^}]*)\}\}/g, (match, key) => {
      const trimmedKey = key.trim();

      // Check if it's a helper call
      const parts = trimmedKey.split(/\s+/);
      if (this.helpers.has(parts[0])) {
        const helper = this.helpers.get(parts[0])!;
        const args = parts.slice(1).map((arg: string) => this.resolveValue(arg, data));
        return String(helper(...args));
      }

      // Regular variable
      return String(this.resolveValue(trimmedKey, data) ?? '');
    });

    // Handle {{#if condition}}...{{/if}}
    result = result.replace(
      /\{\{#if\s+([^}]+)\}\}([\s\S]*?)\{\{\/if\}\}/g,
      (match, condition, content) => {
        const value = this.resolveValue(condition.trim(), data);
        return value ? content : '';
      }
    );

    // Handle {{#each array}}...{{/each}}
    result = result.replace(
      /\{\{#each\s+([^}]+)\}\}([\s\S]*?)\{\{\/each\}\}/g,
      (match, arrayKey, content) => {
        const array = this.resolveValue(arrayKey.trim(), data);
        if (!Array.isArray(array)) {
          return '';
        }

        return array.map((item, index) => {
          const itemData = { ...data, this: item, index };
          return this.render(content, itemData);
        }).join('');
      }
    );

    return result;
  }

  /**
   * Resolve a value from data using dot notation
   */
  private resolveValue(path: string, data: Record<string, any>): any {
    const parts = path.split('.');
    let value: any = data;

    for (const part of parts) {
      if (value === null || value === undefined) {
        return undefined;
      }
      value = value[part];
    }

    return value;
  }
}

