/**
 * Create a template engine with default helpers
 */
export function createTemplateEngine(): TemplateEngine {
  const engine = new TemplateEngine();

  // Register default helpers
  engine.registerHelper('uppercase', (str: string) => str.toUpperCase());
  engine.registerHelper('lowercase', (str: string) => str.toLowerCase());
  engine.registerHelper('capitalize', (str: string) => 
    str.charAt(0).toUpperCase() + str.slice(1)
  );
  engine.registerHelper('camelCase', (str: string) =>
    str.replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))
  );
  engine.registerHelper('pascalCase', (str: string) => {
    const camel = str.replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''));
    return camel.charAt(0).toUpperCase() + camel.slice(1);
  });

  return engine;
}

